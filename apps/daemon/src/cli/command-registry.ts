export type CliCommandMode = "control" | "local" | "events";
export type CliBodyMode = "none" | "optional" | "required";
export type CliOutputMode = "json" | "text";

export interface CliCommandDeclaration {
  readonly id: string;
  readonly family: string;
  readonly command: string;
  readonly mode: CliCommandMode;
  readonly method?: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  readonly path?: (args: readonly string[]) => string;
  readonly positionals: readonly string[];
  readonly body: CliBodyMode;
  readonly response: Schema<unknown>;
  readonly mutating: boolean;
  readonly output: CliOutputMode;
  readonly summary: string;
}

const UnknownSchema: Schema<unknown> = { parse: (value) => value };
const VoidSchema: Schema<undefined> = { parse: (value) => value as undefined };
const TrustListSchema: Schema<unknown> = UnknownSchema;
const OpenApiSchema: Schema<unknown> = UnknownSchema;

function encoded(args: readonly string[], ...parts: Array<string | number>): string {
  return `/api/v1/${parts
    .map((part) => (typeof part === "number" ? args[part] : part))
    .map((part) => encodeURIComponent(part ?? ""))
    .join("/")}`;
}

function command(
  input: Omit<CliCommandDeclaration, "mode" | "body" | "mutating" | "output"> &
    Partial<Pick<CliCommandDeclaration, "mode" | "body" | "mutating" | "output">>,
): CliCommandDeclaration {
  return Object.freeze({
    mode: "control",
    body: "none",
    mutating: false,
    output: "json",
    ...input,
    positionals: Object.freeze([...input.positionals]),
  });
}

