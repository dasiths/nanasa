const commandByName = new Map(
  CLI_COMMAND_REGISTRY.map((item) => [`${item.family}:${item.command}`, item]),
);

export function findCliCommand(family: string, name: string): CliCommandDeclaration | undefined {
  return commandByName.get(`${family}:${name}`);
}

export function commandRegistryHelp(): string {
  const families = new Map<string, CliCommandDeclaration[]>();
  for (const item of CLI_COMMAND_REGISTRY) {
    const entries = families.get(item.family) ?? [];
    entries.push(item);
    families.set(item.family, entries);
  }
  return [...families.entries()]
    .map(([family, entries]) => `${family}: ${entries.map((item) => item.command).join(", ")}`)
    .join("\n");
}
