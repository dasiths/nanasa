export type ControlRouteMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
export type ControlPrincipal = "public" | "operator";
export type IdempotencyPolicy = "forbidden" | "optional" | "required";

export interface ControlRouteDeclaration {
  readonly id: string;
  readonly family: string;
  readonly method: ControlRouteMethod;
  readonly path: `/api/v1${string}`;
  readonly principal: ControlPrincipal;
  readonly schemas: {
    readonly params: z.ZodType;
    readonly query: z.ZodType;
    readonly body: z.ZodType;
    readonly response: z.ZodType;
  };
  readonly bodyLimit: number;
  readonly idempotency: IdempotencyPolicy;
  readonly errors: readonly string[];
  readonly openapi: {
    readonly operationId: string;
    readonly summary: string;
    readonly tags: readonly string[];
    readonly successStatus: number;
  };
  readonly transport?: "http" | "websocket";
}

const KiB = 1_024;
const EmptySchema = z.undefined();
const EmptyObjectSchema = z.object({}).strict();
const IdParamsSchema = z.record(z.string(), z.string().trim().min(1).max(4_096));
const EmptyQuerySchema = EmptyObjectSchema;
const StringQuerySchema = z.record(z.string(), z.string().max(4_096).optional());
const UnknownObjectSchema = z.record(z.string(), z.unknown());
const TrustReceiptSchema = z
  .object({
    id: z.string(),
    repositoryIdentity: z.string(),
    subjectDigest: z.string(),
    principalId: z.string(),
    decision: z.enum(["trusted", "denied", "revoked"]),
    decidedAt: z.string(),
    revokedAt: z.string().optional(),
  })
  .strict();

interface RouteInput {
  id: string;
  family: string;
  method: ControlRouteMethod;
  path: `/api/v1${string}`;
  principal?: ControlPrincipal;
  params?: z.ZodType;
  query?: z.ZodType;
  body?: z.ZodType;
  response?: z.ZodType;
  bodyLimit?: number;
  idempotency?: IdempotencyPolicy;
  errors?: readonly string[];
  summary: string;
  successStatus?: number;
  transport?: "http" | "websocket";
}

function route(input: RouteInput): ControlRouteDeclaration {
  if (input.method !== "GET" && input.idempotency === undefined) {
    throw new Error(`State-changing route ${input.id} must declare an idempotency policy`);
  }
  return Object.freeze({
    id: input.id,
    family: input.family,
    method: input.method,
    path: input.path,
    principal: input.principal ?? "operator",
    schemas: Object.freeze({
      params: input.params ?? EmptyObjectSchema,
      query: input.query ?? EmptyQuerySchema,
      body: input.body ?? EmptySchema,
      response: input.response ?? EmptySchema,
    }),
    bodyLimit: input.bodyLimit ?? 64 * KiB,
    idempotency: input.idempotency ?? "forbidden",
    errors: Object.freeze([...(input.errors ?? [])]),
    openapi: Object.freeze({
      operationId: input.id,
      summary: input.summary,
      tags: Object.freeze([input.family]),
      successStatus: input.successStatus ?? 200,
    }),
    ...(input.transport === undefined ? {} : { transport: input.transport }),
  });
}

