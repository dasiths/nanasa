const routeById = new Map(CONTROL_ROUTE_REGISTRY.map((item) => [item.id, item]));

export function controlRoute(id: string): ControlRouteDeclaration {
  const declaration = routeById.get(id);
  if (declaration === undefined) throw new Error(`Unknown control route: ${id}`);
  return declaration;
}

export function matchControlRoute(
  method: string,
  path: string,
): ControlRouteDeclaration | undefined {
  return CONTROL_ROUTE_REGISTRY.find((declaration) => {
    if (declaration.method !== method) return false;
    const pattern = declaration.path
      .split("/")
      .map((segment) =>
        segment.startsWith(":") ? "[^/]+" : segment.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
      )
      .join("/");
    return new RegExp(`^${pattern}$`).test(path);
  });
}

function openApiPath(path: string): string {
  return path.replace(/:([A-Za-z0-9_]+)/g, "{$1}");
}

function jsonSchema(schema: z.ZodType): unknown {
  return z.toJSONSchema(schema, { unrepresentable: "any" });
}

export function generateControlOpenApi(): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const declaration of CONTROL_ROUTE_REGISTRY) {
    const path = openApiPath(declaration.path);
    const methods = (paths[path] ??= {});
    const bodySchema = declaration.schemas.body;
    methods[declaration.method.toLowerCase()] = {
      operationId: declaration.openapi.operationId,
      summary: declaration.openapi.summary,
      tags: declaration.openapi.tags,
      security:
        declaration.principal === "operator" ? [{ bearerAuth: [] }, { portalSession: [] }] : [],
      "x-nanasa-principal": declaration.principal,
      "x-nanasa-body-limit": declaration.bodyLimit,
      "x-nanasa-idempotency": declaration.idempotency,
      "x-nanasa-errors": declaration.errors,
      ...(bodySchema instanceof z.ZodUndefined
        ? {}
        : {
            requestBody: {
              required: true,
              content: { "application/json": { schema: jsonSchema(bodySchema) } },
            },
          }),
      responses: {
        [String(declaration.openapi.successStatus)]: {
          description: "Success",
          ...(declaration.openapi.successStatus === 204 || declaration.openapi.successStatus === 101
            ? {}
            : {
                content: {
                  "application/json": { schema: jsonSchema(declaration.schemas.response) },
                },
              }),
        },
        default: {
          description: "Versioned control error",
          content: { "application/json": { schema: { type: "object" } } },
        },
      },
    };
  }
  return {
    openapi: "3.1.0",
    info: { title: "Nanasa Control API", version: "1" },
    servers: [{ url: "/" }],
    paths,
    components: {
      securitySchemes: {
        bearerAuth: { type: "http", scheme: "bearer" },
        portalSession: { type: "apiKey", in: "cookie", name: "nanasa_operator" },
      },
    },
  };
}
